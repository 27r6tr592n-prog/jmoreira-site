const categoryId = (slug: string) => {
  const found = categories.find((c) => c.slug === slug)
  if (!found) throw new Error(`Categoria inexistente: ${slug}`)
  return found.id
}

type Spec = { label: string; value: string }

type ProductInput = Omit<
  ProductRow,
  | "id"
  | "category_id"
  | "images"
  | "specs"
  | "created_at"
  | "updated_at"
  | "is_active"
  | "sort_order"
  | "amperage_ah"
  | "voltage_v"
  | "warranty_months"
  | "trade_in_required"
  | "trade_in_surcharge"
  | "compare_at_price"
  | "is_featured"
> & {
  category: string
  specs: Spec[]
  compare_at_price?: number
  is_featured?: boolean
  amperage_ah?: number
  voltage_v?: number
  warranty_months?: number
  trade_in_surcharge?: number
}

let seq = 0
function product(input: ProductInput): ProductRow {
  seq += 1
  const { category, specs, ...rest } = input
  return {
    id: `a1000000-0000-4000-8000-${String(seq).padStart(12, "0")}`,
    category_id: categoryId(category),
    // TODO cliente: substituir pelas fotos reais do produto (3 ângulos).
    images: [1, 2, 3].map((n) => `/produtos/${input.slug}-${n}.svg`),
    specs,
    compare_at_price: input.compare_at_price ?? null,
    is_featured: input.is_featured ?? false,
    amperage_ah: input.amperage_ah ?? null,
    voltage_v: input.voltage_v ?? null,
    warranty_months: input.warranty_months ?? null,
    trade_in_required: input.trade_in_surcharge != null,
    trade_in_surcharge: input.trade_in_surcharge ?? null,
    is_active: true,
    sort_order: seq,
    created_at: CREATED,
    updated_at: CREATED,
    ...rest,
  }
}

